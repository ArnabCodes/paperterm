#!/usr/bin/env bash
set -euo pipefail
if [[ "$(uname -s)" != "Darwin" ]]; then
  printf '%s\n' 'Safari packaging must run on macOS with Xcode. The Safari source ZIP is generated by npm run package on any OS.' >&2
  exit 1
fi
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
bundle_id="${1:?Usage: bash scripts/safari-package.sh your.bundle.identifier [output-directory]}"
output="${2:-$root/artifacts/safari-xcode}"
if [[ ! -f "$root/artifacts/unpacked/safari/manifest.json" ]]; then
  printf '%s\n' 'Run npm run build first.' >&2
  exit 1
fi
if [[ -e "$output" ]]; then
  printf 'Refusing to overwrite an existing project: %s\n' "$output" >&2
  exit 1
fi
if xcrun --find safari-web-extension-packager >/dev/null 2>&1; then
  packager=safari-web-extension-packager
else
  packager=safari-web-extension-converter
fi
xcrun "$packager" "$root/artifacts/unpacked/safari" --project-location "$output" --app-name Pipit --bundle-identifier "$bundle_id" --macos-only --swift --copy-resources --no-prompt --no-open
printf '%s\n' 'Open the generated Xcode project, select your signing team, build/run the app, and enable Pipit in Safari Settings. Distribution signing is separate.'
