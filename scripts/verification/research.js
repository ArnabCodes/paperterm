async (page) => {
  page.setDefaultTimeout(10000);
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const ready = () => page.waitForFunction(() => document.querySelector('#page-total').textContent === '6' && document.querySelector('#loading').hidden && document.querySelector('#engine-status').textContent.includes('Ready'));
  const jump = async number => {
    await page.keyboard.press('p');
    await page.getByRole('combobox', { name: 'Go to page', exact: true }).fill(String(number));
    await page.keyboard.press('Enter');
    await page.waitForFunction(number => document.querySelector('#page-current').textContent === String(number), number);
  };
  const peekCitation = async () => {
    await page.keyboard.press('c');
    await page.getByRole('option').first().waitFor();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#portal').getAttribute('aria-busy') === 'false');
  };
  const selectText = async text => page.evaluate(text => {
    const span = [...document.querySelectorAll('#viewer-container .textLayer span')].find(span => span.firstChild?.nodeType === Node.TEXT_NODE && span.textContent.includes(text));
    if (!span) throw new Error('Selection text not rendered: ' + text);
    const start = span.textContent.indexOf(text);
    const range = document.createRange(); range.setStart(span.firstChild, start); range.setEnd(span.firstChild, start + text.length);
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
    const box = range.getBoundingClientRect();
    return { x: box.x + box.width / 2, y: box.y + box.height / 2 };
  }, text);
  try {
    await page.keyboard.press('Escape');
    await page.goto('http://127.0.0.1:4173/?demo=1&verify=research#page=1');
    await page.reload();
    await ready();
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.keyboard.press('a');
    await page.mouse.move(700, 200);
    await page.keyboard.press('Escape');
    const dock = page.locator('#reader-toolbar');
    const compact = await dock.boundingBox();
    assert(await dock.isVisible() && await page.locator('.dock-core button').count() === 5, 'Dock keeps four reading controls plus a tools launcher visible at rest');
    assert(await page.locator('.dock-more').evaluate(node => node.inert), 'Collapsed extra controls are excluded from keyboard navigation');
    await page.mouse.move(compact.x + compact.width / 2, compact.y + 20);
    await page.waitForFunction(() => document.body.classList.contains('dock-visible'));
    assert(await page.locator('.dock-core').evaluate(node => Math.abs(node.getBoundingClientRect().x + node.clientWidth / 2 - innerWidth / 2) < 1), 'Dock expands around its fixed central controls');
    assert(await page.locator('.dock-more').evaluate(node => !node.inert), 'Hover expands the dock and makes extra tools usable');
    assert(['anchored', 'reduced'].includes(await dock.getAttribute('data-motion')), 'Dock fans out without changing its anchor');
    await page.mouse.move(700, 200);
    await page.waitForFunction(() => !document.body.classList.contains('dock-visible'));
    assert(await dock.isVisible(), 'Dock remains visible after expansion collapses');
    await page.keyboard.press('F6');
    assert(await dock.evaluate(node => node.contains(document.activeElement)), 'F6 still exposes full controls with keyboard focus');
    await page.keyboard.press('Escape');
    const before = await page.evaluate(() => ({ zoom: document.querySelector('#zoom-value').textContent, font: getComputedStyle(document.querySelector('.page-button')).fontSize, ratio: devicePixelRatio, viewport: visualViewport.scale }));
    await page.mouse.move(720, 400);
    await page.keyboard.down('Control'); await page.mouse.wheel(0, -120); await page.keyboard.up('Control');
    await page.waitForFunction(zoom => document.querySelector('#zoom-value').textContent !== zoom, before.zoom);
    const after = await page.evaluate(() => ({ font: getComputedStyle(document.querySelector('.page-button')).fontSize, ratio: devicePixelRatio, viewport: visualViewport.scale }));
    assert(after.font === before.font && after.ratio === before.ratio && after.viewport === before.viewport, 'Real Ctrl+wheel changes PDF magnification without browser/interface zoom');
    const increased = Number((await page.locator('#zoom-value').textContent()).replace('%', ''));
    await page.keyboard.down('Control'); await page.mouse.wheel(0, 120); await page.keyboard.up('Control');
    await page.waitForFunction(zoom => parseInt(document.querySelector('#zoom-value').textContent) < zoom, increased);
    assert(true, 'Ctrl+wheel zooms the document in both directions');
    await page.keyboard.press('a'); await jump(1);
    const original = await page.locator('#viewer-container').boundingBox();
    const originalTop = await page.locator('#viewer-container').evaluate(node => node.scrollTop);
    await peekCitation();
    const popup = await page.locator('#portal').boundingBox();
    assert(Math.abs(popup.width / popup.height - 1.5) < .01 && Math.abs(popup.x + popup.width / 2 - 720) < 1 && !await page.locator('body').evaluate(node => node.classList.contains('has-portal')), 'Reference quick look is centered with the current app aspect ratio');
    const unchanged = await page.locator('#viewer-container').boundingBox();
    assert(unchanged.width === original.width && await page.locator('#viewer-container').evaluate(node => node.scrollTop) === originalTop, 'Popup preserves the main page size and exact scroll position');
    await page.keyboard.press('Alt+ArrowDown');
    await page.waitForFunction(label => document.querySelector('#portal-title')?.textContent === label && !document.querySelector('#portal')?.hidden, "Reference [2]");
    await page.keyboard.press('Alt+ArrowUp');
    await page.waitForFunction(label => document.querySelector('#portal-title')?.textContent === label && !document.querySelector('#portal')?.hidden, "Reference [1]");
    assert(true, 'Preview navigation moves between lookup results in both directions');
    await page.keyboard.press('P');
    await page.waitForFunction(() => document.body.classList.contains('has-portal'));
    await page.waitForFunction(width => document.querySelector('#viewer-container').clientWidth < width, original.width);
    assert(await page.getByRole('button', { name: 'Pin preview beside paper (Shift+P)', exact: true, includeHidden: true }).getAttribute('aria-pressed') === 'true', 'Preview can be pinned beside the document');
    await page.keyboard.press('P');
    await page.waitForFunction(() => !document.body.classList.contains('has-portal') && document.querySelector('#portal').getAttribute('aria-busy') === 'false');
    assert((await page.locator('#viewer-container').boundingBox()).width === original.width, 'Unpinning returns to the floating popup');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '6');
    await page.keyboard.press('Alt+ArrowLeft');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '1');
    assert(true, 'Enter follows a preview and reading history returns to its source');
    await page.getByRole('link', { name: 'Open equation (2)', exact: true }).click({ button: 'right' });
    await page.waitForFunction(label => document.querySelector('#portal-title')?.textContent === label && !document.querySelector('#portal')?.hidden, "Linked passage");
    assert(await page.locator('#portal-page').textContent() === 'Page 3', 'Right-clicking an embedded link previews its destination');
    await page.keyboard.press('Escape');
    await page.getByRole('link', { name: 'Open equation (2)', exact: true }).click({ button: 'middle' });
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '3');
    await page.keyboard.press('Alt+ArrowLeft');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '1');
    assert(true, 'Middle-click follows an internal reference and keeps a return point');
    const reference = await selectText('(2)');
    await page.mouse.click(reference.x, reference.y, { button: 'right' });
    await page.waitForFunction(label => document.querySelector('#portal-title')?.textContent === label && !document.querySelector('#portal')?.hidden, "Equation (2)");
    assert(await page.locator('#portal-page').textContent() === 'Page 3', 'Right-click resolves an unlinked equation number');
    await page.keyboard.press('Escape');
    await selectText('(2)'); await page.keyboard.press('Alt+Enter');
    await page.waitForFunction(label => document.querySelector('#portal-title')?.textContent === label && !document.querySelector('#portal')?.hidden, "Equation (2)");
    await page.keyboard.press('Escape');
    assert(true, 'Selected references can be previewed entirely with the keyboard');
    await selectText('(2)'); await page.keyboard.press('Alt+Shift+Enter');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '3');
    assert(true, 'Alt+Shift+Enter jumps to the selected reference definition');
    await page.keyboard.press('g'); await page.keyboard.press('L');
    await page.getByRole('dialog', { name: 'Citation graph', exact: true }).waitFor();
    assert((await page.locator('#research-summary').textContent()).startsWith('4 bibliography entries · 2 numeric mentions · 1 citing pages'), 'Citation graph excludes bibliography definitions from mention counts');
    assert(await page.locator('#citation-graph .graph-edge').count() === 1, 'Graph connects the citing page to its bibliography entry');
    await page.getByRole('searchbox', { name: 'Filter references', exact: true }).fill('Bush');
    assert(await page.locator('.reference-card').count() === 1, 'Reference graph filters by bibliography author');
    await page.getByRole('button', { name: 'Quick look', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#portal').getAttribute('aria-busy') === 'false');
    assert(await page.locator('#portal-page').textContent() === 'Page 6', 'Graph bibliography entries open a quick look');
    await page.keyboard.press(':');
    await page.getByRole('combobox', { name: 'Find a command', exact: true }).fill('preview citation mentions');
    await page.keyboard.press('Enter');
    await page.locator('.backlink').first().click();
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '1');
    assert(true, 'Citation backlinks jump to the actual citing passage');
    await page.keyboard.press('Escape');
    await page.keyboard.press('g'); await page.keyboard.press('t');
    await page.getByRole('combobox', { name: 'Search document contents', exact: true }).fill('References');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '6');
    assert(true, 'Searchable contents navigate directly to a section');
    await jump(1); await page.keyboard.press('g'); await page.keyboard.press('s');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '2');
    assert(true, 'Next-section shortcut follows the embedded outline');
    await jump(1); await page.keyboard.press('g'); await page.keyboard.press('e');
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '3');
    assert(true, 'Next-equation shortcut finds the definition instead of its earlier mention');
    await jump(1); await page.keyboard.press('a');
    await selectText('Reading a technical paper');
    await page.keyboard.press('q');
    const notebook = page.getByRole('dialog', { name: 'Research notebook', exact: true });
    await notebook.waitFor();
    const notes = notebook.locator('.notebook-card');
    const count = await notes.count();
    const latest = notes.last();
    assert((await latest.locator('blockquote').textContent()).includes('Reading a technical paper'), 'Selected passage is captured with its source page');
    await latest.locator('textarea').fill('A useful research note for verification.');
    await page.screenshot({ path: 'output/playwright/research-notebook.png', animations: 'disabled' });
    const downloadEvent = page.waitForEvent('download');
    await notebook.getByRole('button', { name: 'Export Markdown', exact: true }).click();
    const exported = await downloadEvent;
    await exported.saveAs('output/playwright/research-notebook.md');
    assert(exported.suggestedFilename().endsWith('-notebook.md'), 'Notebook exports passages and notes as a local Markdown file');
    await page.keyboard.press('Escape'); await page.reload(); await ready();
    await page.keyboard.press('Q');
    assert(await notebook.locator('.notebook-card').count() === count && await notebook.locator('textarea').last().inputValue() === 'A useful research note for verification.', 'Notebook notes and quotes survive reload');
    await notebook.locator('[data-jump]').last().click();
    await page.waitForFunction(() => document.querySelector('#page-current').textContent === '1');
    assert(true, 'Notebook passages retain a working jump back to their source');
    await page.keyboard.press('Q'); await notebook.locator('[data-delete]').last().click(); await page.keyboard.press('Escape');
    await page.keyboard.press('a');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.keyboard.press('F6');
    await page.waitForFunction(() => {
      const dock = document.querySelector('#reader-toolbar').getBoundingClientRect();
      const more = document.querySelector('.dock-more').getBoundingClientRect();
      const content = document.querySelector('.dock-more-content');
      return dock.left >= 0 && dock.right <= innerWidth && more.left >= 0 && more.right <= innerWidth && content.scrollWidth <= content.clientWidth;
    });
    assert(await dock.evaluate(node => node.getBoundingClientRect().left >= 0 && node.getBoundingClientRect().right <= innerWidth) && await page.locator('.dock-more-content').evaluate(node => node.scrollWidth <= node.clientWidth) && await page.locator('.dock-more').evaluate(node => node.getBoundingClientRect().left >= 0 && node.getBoundingClientRect().right <= innerWidth), 'Compact and expanded controls fit a narrow window');
    await page.keyboard.press('Escape'); await peekCitation();
    assert(await page.locator('#portal').evaluate(node => node.getBoundingClientRect().left >= 0 && node.getBoundingClientRect().right <= innerWidth), 'Quick-look popup fits a phone-sized viewport');
    await page.screenshot({ path: 'output/playwright/research-compact-preview.png', animations: 'disabled' });
    await page.keyboard.press('Escape'); await page.setViewportSize({ width: 1440, height: 960 });
    return { passed: checks.length, checks };
  } catch (error) { throw new Error(`After ${checks.length} checks (${checks.at(-1)}): ${error.message}`); }
}
