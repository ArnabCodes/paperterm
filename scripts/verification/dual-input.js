async (page) => {
  const base = new URL(page.url()).origin, checks = [], errors = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  const hud = page.locator('#demo-input-display');
  const mode = name => page.locator(`.demo-modes [data-input-mode=${name}]`);
  page.on('pageerror', error => errors.push(String(error)));
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base);
  assert(await page.locator('#features button').count() === 0, 'Feature cards do not contain a second, inconsistent demo system');
  await page.locator('[data-show-demo=palette]').click();
  assert(await page.locator('#tab-palette').getAttribute('aria-selected') === 'true', 'Feature-card link opens the matching full mouse/keyboard demo');
  await page.locator('#tab-peek').click();
  await mode('mouse').click();
  assert(await page.locator('#stage-portal').isVisible() && await page.locator('.demo-pointer').isVisible(), 'Mouse preview demonstrates a click with a visible pointer');
  assert((await hud.textContent()).includes('Mouse'), 'Mouse action is labeled separately from keyboard input');
  await mode('keyboard').click();
  assert((await hud.textContent()).includes('FA') && await page.locator('#stage-portal').isVisible(), 'Keyboard preview demonstrates the actual F then hint sequence');
  assert(await page.locator('.demo-pointer').isHidden(), 'Keyboard demonstration does not show a mouse pointer');
  await page.locator('#scene-peek').focus(); await page.keyboard.press('Escape');
  await page.keyboard.press('F');
  assert(await page.locator('#demo-reference-hint').isVisible(), 'Actual F key displays the sample reference hint');
  await page.keyboard.press('a');
  assert(await page.locator('#stage-portal').isVisible() && (await hud.textContent()).includes('FA'), 'Typing the hint opens the preview and updates corner keys');
  await page.keyboard.press('Escape'); await page.locator('#stage-reference').focus(); await page.keyboard.press('Space');
  assert((await hud.textContent()).includes('Space') && await page.locator('#stage-portal').isVisible(), 'Space activation displays the actual key, not an invented Enter press');
  const prior = await hud.textContent();
  await page.locator('h1').click(); await page.keyboard.press('F');
  assert(await hud.textContent() === prior, 'Typing outside the emulated screen is not captured by the key display');
  await page.locator('#tab-flow').click(); await mode('mouse').click();
  assert(await page.locator('#stage-command').isVisible(), 'Mouse command button demonstrates opening the palette');
  await mode('keyboard').click();
  assert((await hud.textContent()).includes(':'), 'Keyboard command demo shows colon rather than a mouse click');
  await page.locator('#scene-flow').focus(); await page.keyboard.press('Escape'); await page.keyboard.press('j');
  assert((await hud.textContent()).includes('j'), 'Actual navigation key is shown in the corner');
  await page.locator('#tab-palette').click(); await mode('mouse').click();
  assert(await page.locator('.reader-stage').getAttribute('data-palette') === 'night', 'Mouse theme demo selects Night');
  await mode('keyboard').click();
  assert((await hud.textContent()).includes('gd'), 'Keyboard theme demo shows the real g d shortcut');
  await page.locator('#scene-palette').focus(); await page.keyboard.press('g'); await page.keyboard.press('d');
  assert(await page.locator('.reader-stage').getAttribute('data-palette') === 'night', 'Actual sequential theme shortcut changes the palette');
  await page.locator('#tab-map').click(); await mode('mouse').click();
  assert((await page.locator('#network-detail').textContent()).includes('cites'), 'Mouse map demo selects a citing paper');
  await mode('keyboard').click();
  assert((await hud.textContent()).includes('gc→↵'), 'Keyboard map demo shows open-map, arrow and Enter keys');
  await page.locator('#scene-map').focus(); await page.keyboard.press('g'); await page.keyboard.press('c'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter');
  assert((await page.locator('#network-detail').textContent()).includes('foundation'), 'Actual graph arrow/Enter traversal selects a paper');
  await page.locator('#tab-peek').click(); await page.locator('#tour-toggle').click();
  await page.waitForFunction(() => document.querySelector('.reader-stage').dataset.inputMode === 'mouse' && !document.querySelector('#stage-portal').hidden);
  assert(true, 'Guided tour starts with the mouse demonstration');
  await page.waitForFunction(() => document.querySelector('.reader-stage').dataset.inputMode === 'keyboard' && !document.querySelector('#demo-reference-hint').hidden);
  assert(true, 'Guided tour then prepares keyboard hints');
  await page.waitForFunction(() => document.querySelector('#demo-input-display').textContent.includes('FA') && !document.querySelector('#stage-portal').hidden);
  assert(true, 'Guided tour completes the keyboard counterpart');
  await page.locator('#tour-toggle').click();
  assert(await page.locator('.showcase').getAttribute('data-playing') === 'false', 'Tour can be interrupted');
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px: input controls and key display fit`);
    const corner = await hud.boundingBox(), frame = await page.locator('.reader-stage').boundingBox();
    assert(corner.x >= frame.x && corner.x + corner.width <= frame.x + frame.width + 1, `${width}px: keystroke display remains inside the emulated screen`);
    if (width === 1440) await page.locator('.reader-stage').screenshot({ path: 'output/playwright/dual-input-keyboard.png' });
    if (width === 390) await page.locator('.reader-stage').screenshot({ path: 'output/playwright/dual-input-phone.png' });
  }
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto(base); await page.locator('.showcase').scrollIntoViewIfNeeded();
  assert(await page.locator('#tour-toggle').getAttribute('aria-pressed') === 'false', 'Reduced motion does not autoplay the tour');
  await mode('mouse').click();
  assert(await page.locator('.demo-pointer').evaluate(node => getComputedStyle(node).transitionDuration === '0s'), 'Reduced motion removes pointer movement animation');
  await page.locator('.reader-stage').screenshot({ path: 'output/playwright/dual-input-mouse.png' });
  assert(errors.length === 0, `No JavaScript errors: ${errors.join('; ')}`);
  return { passed: checks.length, checks };
}
