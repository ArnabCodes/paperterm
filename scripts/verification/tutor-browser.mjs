import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFileSync, mkdirSync } from 'node:fs';
const output='output/playwright/tutor'; mkdirSync(output,{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror',error=>errors.push(error.message));
const state=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
const completed=async id=>{await page.waitForFunction(id=>JSON.parse(window.render_game_to_text()).completed.includes(id),id,{timeout:15000}); console.log('PASS real action:',id);};
const next=()=>page.locator('[data-tutor=next]').click();
const key=async value=>{await page.locator('#viewer-container').focus();await page.keyboard.press(value);};
try {
await page.goto('http://127.0.0.1:4173/');
await key(':');await page.locator('#palette-input').fill('Tutor');await page.keyboard.press('Enter');
await page.locator('#tutor-start').click();await page.locator('#tutor-panel').waitFor();
assert.equal((await state()).xp,0);
await page.screenshot({path:`${output}/01-coach.png`});
await key('p');await page.locator('#palette-input').fill('2');await page.keyboard.press('Enter');await completed('navigate');await next();
await key('/');await page.locator('#find-input').fill('coherence');await completed('search');await page.keyboard.press('Escape');await next();
await key('e');await page.locator('#palette-input').fill('2');await page.waitForTimeout(600);await page.keyboard.press('Enter');await completed('preview');
await page.screenshot({path:`${output}/02-lens.png`});await next();
await key('Shift+P');await completed('pin');await next();
await page.locator('#portal-scroll').focus();await page.keyboard.press('Enter');await key('Alt+ArrowLeft');await completed('trail');await next();
await key('g');await page.keyboard.press('d');await completed('theme');await next();
await key('b');await completed('bookmark');await next();
await key('Shift+Q');await page.locator('.notebook-add').click();await page.locator('.notebook-note').last().fill('The weighted score links the two traces.');await completed('notes');await page.keyboard.press('Escape');await next();
await key('r');await completed('ruler');await next();
await key('g');await page.keyboard.press('2');await completed('spread');
assert.equal((await state()).xp,300);assert.equal((await state()).rank,'Atlas Explorer');
await page.screenshot({path:`${output}/03-complete.png`});
await page.locator('[data-tutor=pause]').click();assert.equal((await state()).mode,'inactive');
await page.reload();await key(':');await page.locator('#palette-input').fill('Tutor');await page.keyboard.press('Enter');
assert.match(await page.locator('#tutor-intro').innerText(),/300 XP/);await page.locator('#tutor-start').click();await page.locator('#tutor-panel').waitFor();
assert.equal((await state()).xp,300);
await page.locator('#tutor-panel summary').click();await page.locator('[data-tutor=restart]').click();await page.locator('[data-tutor=confirm-reset]').click();
assert.equal((await state()).xp,0);
await page.locator('#tutor-panel summary').click();await page.locator('[data-mission="7"]').click();
await key('Shift+Q');assert.match(await page.locator('.notebook-note').last().inputValue(),/weighted score/);await page.waitForTimeout(400);assert.equal((await state()).xp,0,'Opening existing saved notes does not award XP');await page.keyboard.press('Escape');
await page.locator('#tutor-panel summary').click();await page.locator('[data-mission="0"]').click();
await page.locator('[data-tutor=skip]').click();assert.deepEqual((await state()).skipped,['navigate']);assert.equal((await state()).xp,0);
await page.locator('[data-tutor=hint]').click();assert.equal(await page.locator('.tutor-hint').isVisible(),true);
await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'});await page.screenshot({path:`${output}/04-mobile.png`});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
assert.deepEqual(errors,[]);writeFileSync(`${output}/result.json`,JSON.stringify({state:await state(),errors,passed:true},null,2));
console.log('PASS :Tutor, all 10 missions, 300 XP, pause/resume, persistent progress, reset, skip, hints, mobile and no page errors.');
} finally { await browser.close(); }
