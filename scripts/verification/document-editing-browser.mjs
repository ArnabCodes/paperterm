import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import { PDFDocument } from 'pdf-lib';
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs';

const base = process.argv[2] || 'http://127.0.0.1:5173/';
const output = resolve('output/playwright/document-editing');
mkdirSync(output, { recursive: true });
const source = await PDFDocument.create();
const sourcePage = source.addPage([612, 792]);
sourcePage.drawText('Pipit document editing smoke fixture', { x: 72, y: 720, size: 18 });
sourcePage.drawText('A second selectable annotation line', { x: 72, y: 682, size: 12 });
source.addPage([612, 792]).drawText('Second page for deletion and undo coverage', { x: 72, y: 720, size: 16 });
const fixtureForm = source.getForm();
fixtureForm.createTextField('Researcher').addToPage(sourcePage, { x: 72, y: 650, width: 280, height: 28 });
fixtureForm.updateFieldAppearances();
const inputPath = resolve(output, 'form-fixture.pdf');
writeFileSync(inputPath, await source.save());

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const startCommand = async query => {
    await page.locator('#viewer-container').evaluate(node => node.focus());
    await page.keyboard.press(':');
    await page.locator('#palette[open]').waitFor();
    await page.locator('#palette-input').fill(query);
    await page.locator('[role=option]').first().waitFor();
    await page.keyboard.press('Enter');
  };
  await page.goto(base);
  await page.locator('#file-input').setInputFiles(inputPath);
  await page.locator('#viewer .page[data-page-number="1"]').waitFor();
  await page.waitForTimeout(800);
  const field = page.locator('.annotationLayer input').first();
  await field.waitFor();
  await field.fill('A. Example');
  await page.waitForTimeout(850);

  await startCommand('Save edited PDF copy');
  const saveDownloadPromise = page.waitForEvent('download');
  await page.keyboard.press('Enter');
  const download = await saveDownloadPromise;
  const savedPath = await download.path();
  const saved = await PDFDocument.load(new Uint8Array(readFileSync(savedPath)));
  assert.equal(saved.getForm().getTextField('Researcher').getText(), 'A. Example', 'saved PDF copy retains filled AcroForm value');
  console.log('PASS form field saves into the downloaded PDF copy');
  await startCommand('Undo last PDF edit');
  await page.waitForFunction(() => document.querySelector('.annotationLayer input')?.value === '');
  assert.equal(await page.locator('.page-editor-dialog[open]').count(), 0, 'undo keeps the closed Pages window closed');
  await startCommand('Redo PDF edit');
  await page.waitForFunction(() => document.querySelector('.annotationLayer input')?.value === 'A. Example');
  console.log('PASS form changes undo and redo through the PDF edit history');

  await page.locator('#viewer-container').evaluate(node => node.focus());
  await page.keyboard.press('Shift+Q');
  const notebook = page.locator('#notebook-panel');
  await notebook.waitFor({ state: 'visible' });
  await page.locator('.notebook-add').click();
  await page.locator('.notebook-note').last().fill('Review with the group on Friday.');
  assert.equal(await page.locator('.notebook-timestamp').count(), 1);
  assert.ok(await page.locator('.notebook-timestamp').first().getAttribute('datetime'));
  assert.ok(await notebook.evaluate(node => node.getBoundingClientRect().width >= 280));
  console.log('PASS notebook opens beside the paper and shows dated notes');
  await page.keyboard.press('Escape');

  await startCommand('Vimium compatibility');
  await startCommand('Visual mode');
  await page.keyboard.press('j');
  await page.keyboard.press('h');
  await page.waitForFunction(() => Array.from({ length: localStorage.length }, (_, index) => localStorage.key(index)).some(key => {
    if (!key?.startsWith('pipit.notebook.v1:')) return false;
    try { return JSON.parse(localStorage.getItem(key) || '[]').some(entry => entry.kind === 'highlight'); } catch { return false; }
  }));
  await page.keyboard.press('Escape');
  await startCommand('Vimium compatibility');
  console.log('PASS Vimium compatibility keeps command-launched Visual mode and keyboard highlights working');
  await startCommand('Add text to PDF copy');
  await page.locator('.markup-dialog textarea').fill('Margin note: verify the result.');
  await page.locator('dialog.markup-dialog[open] button[type=submit]').click();
  await page.locator('.placement-hud').waitFor({ state: 'visible' });
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Enter');
  await page.locator('#toast').filter({ hasText: 'Add text stamp' }).waitFor({ state: 'visible' });
  await startCommand('Sign');
  await page.locator('.markup-dialog input[name=name]').fill('A. Example');
  await page.locator('dialog.markup-dialog[open] button[type=submit]').click();
  await page.locator('.placement-hud').waitFor({ state: 'visible' });
  await page.keyboard.press('Enter');
  await page.locator('#toast').filter({ hasText: 'Add signature stamp' }).waitFor({ state: 'visible' });
  await startCommand('Save edited PDF copy');
  const stampDownloadPromise = page.waitForEvent('download');
  await page.keyboard.press('Enter');
  const stampDownload = await stampDownloadPromise;
  const stampPath = await stampDownload.path();
  const stampTask = pdfjs.getDocument({ data: new Uint8Array(readFileSync(stampPath)), standardFontDataUrl: new URL('../../node_modules/pdfjs-dist/standard_fonts/', import.meta.url).href });
  const stampPdf = await stampTask.promise;
  const stampOps = await (await stampPdf.getPage(1)).getOperatorList();
  assert.ok(stampOps.fnArray.filter(operation => operation === pdfjs.OPS.paintImageXObject).length >= 2, 'saved PDF contains separate text and signature stamp images');
  await stampTask.destroy();
  console.log('PASS keyboard-placed text and visible signature stamps are present in the saved PDF copy');

  await startCommand('View edit history');
  await page.locator('.page-editor-dialog[open]').waitFor();
  const editHistory = page.locator('.page-edit-history');
  assert.equal(await editHistory.getAttribute('open'), '');
  const historyText = await editHistory.locator('[data-history-list]').innerText();
  assert.match(historyText, /Add text stamp/);
  assert.match(historyText, /Add signature stamp/);
  assert.match(historyText, /Fill PDF form fields/);
  assert.match(historyText, /Add notebook note/);
  assert.match(historyText, /Edit notebook note/);
  assert.match(historyText, /Add highlight/);
  await page.locator('.page-card[data-editor-page="2"]').click();
  await page.keyboard.press('Delete');
  await page.waitForFunction(() => document.querySelector('#page-total')?.textContent === '1');
  await page.waitForFunction(() => document.querySelector('.page-editor-dialog[open]')?.dataset.busy === 'false');
  await page.keyboard.press('Control+z');
  await page.waitForFunction(() => document.querySelector('#page-total')?.textContent === '2');
  await page.waitForFunction(() => document.querySelector('.page-editor-dialog[open]')?.dataset.busy === 'false');
  await page.keyboard.press('Control+Shift+z');
  await page.waitForFunction(() => document.querySelector('#page-total')?.textContent === '1');
  console.log('PASS page deletion, undo and redo preserve the editable document history');
  const dock = page.locator('#reader-toolbar');
  await page.locator('.page-editor-close').click();
  await page.locator('[data-dock-toggle]').click();
  const editGroup = page.locator('[data-dock-group="pages"]');
  await editGroup.waitFor({ state: 'visible' });
  await editGroup.hover();
  const dockActions = page.locator('#dock-details [data-dock-run]');
  await dockActions.first().waitFor();
  assert.ok(await dockActions.evaluateAll(buttons => buttons.length >= 8));
  assert.ok(await dockActions.first().getAttribute('aria-label'));
  assert.equal(await dockActions.first().evaluate(button => getComputedStyle(button, '::after').content === 'none'), false);
  console.log('PASS timestamped edit history and icon-first dock actions are exposed');

  await startCommand('Tutor');
  await page.locator('#tutor-intro[open]').waitFor();
  await page.locator('[data-tutor="advanced"]').click();
  await page.locator('#tutor-panel').waitFor();
  await page.waitForFunction(() => document.querySelector('#tutor-panel')?.dataset.preparing === 'false');
  await page.locator('.tutor-levels summary').click();
  await page.locator('.tutor-levels [data-mission="3"]').click();
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).mission === 'markup-highlight' && document.querySelector('#tutor-panel')?.dataset.preparing === 'false');
  await page.keyboard.press('v');
  await page.keyboard.press('j');
  await page.keyboard.press('h');
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).completed.includes('markup-highlight'));
  console.log('PASS advanced tutorial teaches and verifies a keyboard-only highlight');

  assert.deepEqual(errors, [], `browser errors: ${errors.join('; ')}`);
  console.log('PASS no browser page errors');
} finally {
  await browser.close();
}
