async (page) => {
  const checks = [], errors = [], timings = [];
  const base = new URL('.', page.url()).href.replace(/\/$/, '');
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(String(error)));
  const ready = () => page.waitForFunction(() => !document.querySelector('#portal').hidden && document.querySelector('#portal').getAttribute('aria-busy') === 'false');
  const indexed = total => page.waitForFunction(total => document.querySelector('#page-total')?.textContent === total && document.querySelector('#engine-status')?.textContent.includes('Ready'), total);
  const peek = async query => {
    const start = Date.now();
    await page.keyboard.press('e'); await page.getByRole('combobox', { name: 'Find an equation', exact: true }).fill(query);
    await page.getByRole('option').first().waitFor(); await page.keyboard.press('Enter'); await ready();
    timings.push(Date.now() - start);
  };
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${base}/index.html?demo=1&verify=${Date.now()}#page=1`); await indexed('6');
  await page.mouse.move(700, 300); await page.keyboard.press('Escape');
  const core = page.locator('.dock-core');
  const before = await core.boundingBox();
  const search = await page.locator('.dock-core [data-action=search]').boundingBox();
  await page.mouse.move(search.x + search.width / 2, search.y + search.height / 2);
  await page.waitForTimeout(750);
  const after = await core.boundingBox();
  assert(Math.abs(before.x - after.x) < .5 && Math.abs(before.width - after.width) < .5, 'Hover expansion never moves core dock targets');
  const hit = await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.closest('button')?.getAttribute('data-action'), { x: search.x + search.width / 2, y: search.y + search.height / 2 });
  assert(hit === 'search', 'Hovered search icon remains under the pointer');
  await page.mouse.click(search.x + search.width / 2, search.y + search.height / 2);
  assert(await page.locator('#find-bar').isVisible(), 'Clicking the original target opens search');
  await page.keyboard.press('Escape'); await page.keyboard.press('F6');
  await page.locator('[data-dock-group=layout]').click();
  assert(await page.locator('#dock-details').isVisible(), 'Dock exposes grouped named commands');
  await page.locator('[data-dock-run=spread]').click();
  assert(await page.locator('.spread').count() > 0, 'Two-page view is available from dock');
  await page.keyboard.press('g'); await page.keyboard.press('2');
  await page.keyboard.press('F6'); await page.locator('[data-dock-group=references]').click();
  await page.keyboard.press('Escape');
  assert(await page.locator('#dock-details').isHidden() && await page.locator('[data-dock-group=references]').evaluate(node => node === document.activeElement), 'Escape returns focus from commands to category');
  await page.waitForTimeout(750); await page.screenshot({ path: 'output/playwright/refinement-dock.png' });
  await page.keyboard.press('Escape');
  await page.locator('#file-input').setInputFiles('output/playwright/fixtures/column-previews.pdf'); await indexed('1');
  await page.keyboard.press('F');
  const count = await page.locator('.link-hint').count();
  assert(count > 0, 'F offers text-based references without PDF hyperlinks');
  await page.keyboard.type(await page.locator('.link-hint').first().textContent()); await ready();
  assert(await page.locator('#portal-canvas').getAttribute('data-column') === 'left', 'Unified lens selects the target column');
  const mainTop = await page.locator('#viewer-container').evaluate(node => node.scrollTop);
  const scroll = page.locator('#portal-scroll');
  const initial = await scroll.evaluate(node => ({ top: node.scrollTop, height: node.clientHeight, total: node.scrollHeight }));
  assert(initial.total > initial.height + 100, 'Object-only viewport retains scrollable page context');
  await page.keyboard.press('j');
  assert(await scroll.evaluate(node => node.scrollTop) > initial.top, 'j scrolls within the lens');
  await page.keyboard.press('k');
  assert(Math.abs(await scroll.evaluate(node => node.scrollTop) - initial.top) <= 1, 'k returns to the object crop');
  await scroll.evaluate(node => { node.scrollTop = 0; }); await page.keyboard.press('d');
  assert(await scroll.evaluate(node => node.scrollTop) > 0, 'Half-page navigation respects preview focus');
  assert(await page.locator('#viewer-container').evaluate(node => node.scrollTop) === mainTop, 'Preview scrolling leaves main reading position intact');
  assert(await page.locator('#portal-canvas').evaluate(node => node.width * node.height <= 8_020_000), 'Context render stays within its bounded pixel budget');
  await page.keyboard.press('Escape'); await peek('2');
  const crop = await page.locator('#portal-canvas').evaluate(node => JSON.parse(node.dataset.crop));
  assert(crop.column === 'right' && crop.height < .2, 'Equation lens initially isolates a compact right-column object');
  assert(await scroll.evaluate(node => node.scrollTop) > 0, 'Initial scroll aligns to the object, not page top');
  await page.locator('#portal').evaluate(node => Promise.all(node.getAnimations().map(animation => animation.finished.catch(() => {}))));
  await page.screenshot({ path: 'output/playwright/refinement-equation.png' });
  await page.keyboard.press('P'); await ready();
  await page.locator('#portal').evaluate(node => Promise.all(node.getAnimations().map(animation => animation.finished.catch(() => {}))));
  await page.getByRole('separator', { name: 'Resize reference panel', exact: true }).focus();
  const width = await page.locator('#portal').evaluate(node => node.clientWidth);
  await page.keyboard.press('ArrowLeft'); await ready();
  assert(await page.locator('#portal').evaluate(node => node.clientWidth) > width, 'Pinned lens remains keyboard resizable');
  await page.keyboard.press('Escape');
  await page.goto(`${base}/index.html?demo=1&verify=${Date.now()}#page=1`); await indexed('6');
  await peek('2'); await page.keyboard.press('Alt+PageDown'); await ready();
  assert((await page.locator('#portal').getAttribute('aria-label')).startsWith('Page 4 context'), 'Lens can independently continue to the next paper page');
  assert(await page.locator('#page-current').textContent() === '1', 'Independent preview navigation leaves main page unchanged');
  await page.keyboard.press('Escape');
  await page.locator('#viewer-container').evaluate(node => node.scrollTop = 155);
  const original = await page.locator('#viewer-container').evaluate(node => node.scrollTop);
  const zoom = await page.locator('#zoom-value').textContent();
  await page.keyboard.press('p'); await page.getByRole('combobox', { name: 'Go to page', exact: true }).fill('4'); await page.keyboard.press('Enter'); await page.keyboard.press('+'); await page.keyboard.press('Alt+ArrowLeft');
  assert(await page.locator('#zoom-value').textContent() === zoom, 'History restores the original magnification');
  assert(Math.abs(await page.locator('#viewer-container').evaluate(node => node.scrollTop) - original) < 3, 'History restores precise scroll coordinates after zoom');
  await page.keyboard.press('Q');
  const notebook = page.getByRole('dialog', { name: 'Research notebook', exact: true });
  await notebook.locator('.notebook-add').click(); await notebook.locator('textarea').last().fill('Portable note α <script>literal</script>');
  await notebook.locator('.notebook-portable summary').click();
  const entries = await notebook.locator('.notebook-card').count();
  const download = page.waitForEvent('download'); await notebook.locator('.notebook-backup').click();
  const backup = await download; await backup.saveAs('output/playwright/refinement-notebook.json');
  await notebook.locator('.notebook-delete').last().click();
  assert(await notebook.locator('.notebook-card').count() === entries - 1, 'Deleting a note updates the notebook');
  await notebook.locator('.notebook-undo').click();
  assert(await notebook.locator('textarea').last().inputValue() === 'Portable note α <script>literal</script>', 'Undo restores deleted note and literal text');
  await notebook.locator('.notebook-redo').click();
  assert(await notebook.locator('.notebook-card').count() === entries - 1, 'Redo reapplies deletion');
  await notebook.locator('.notebook-import-file').setInputFiles('output/playwright/refinement-notebook.json');
  await page.waitForFunction(count => document.querySelectorAll('.notebook-card').length === count, entries);
  assert(await notebook.locator('textarea').last().inputValue() === 'Portable note α <script>literal</script>', 'Export/import round trip restores anchored note without HTML execution');
  await notebook.locator('.notebook-import-file').setInputFiles('output/playwright/refinement-notebook.json');
  await page.waitForTimeout(100);
  assert(await notebook.locator('.notebook-card').count() === entries, 'Reimport does not duplicate notes');
  const markdown = page.waitForEvent('download'); await notebook.locator('.notebook-export').click();
  await (await markdown).saveAs('output/playwright/refinement-notebook.md');
  await page.keyboard.press('Escape');
  await page.reload(); await indexed('6'); await page.keyboard.press('Q');
  assert(await notebook.locator('textarea').last().inputValue() === 'Portable note α <script>literal</script>', 'Imported notes survive reload');
  await page.keyboard.press('Escape');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await page.keyboard.press('F6');
    await page.locator('[data-dock-group=layout]').click();
    assert(await page.locator('#dock-details').evaluate(node => { const box = node.getBoundingClientRect(); return box.left >= 0 && box.right <= innerWidth && box.top >= 0; }), `Dock tools fit ${width}px viewport`);
    await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
  }
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.keyboard.press('F6');
  assert(await page.locator('.dock-category').first().evaluate(node => parseFloat(getComputedStyle(node).transitionDuration) <= .001), 'Reduced motion removes fan transitions');
  assert(errors.length === 0, `No runtime errors: ${errors.join('; ')}`);
  return { checks: checks.length, passed: checks, equationOpenMilliseconds: timings };
}
