async (page) => {
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto('http://127.0.0.1:4173/?demo=1&review=files');
  await page.waitForFunction(() => document.querySelector('#engine-status')?.textContent.includes('Ready'));
  let nativePickers = 0;
  page.on('filechooser', () => nativePickers++);
  await page.keyboard.press('o');
  await page.locator('#file-browser').waitFor({ state: 'visible' });
  assert(nativePickers === 0, 'Open displays the internal browser without a system picker');
  assert(await page.locator('.files-columns > section').count() === 3, 'Three labeled exploration columns');
  await page.evaluate(() => {
    const pdf = { kind: 'file', name: 'Research.pdf', getFile: async () => new File([await (await fetch('sample.pdf')).blob()], 'Research.pdf', { type: 'application/pdf' }) };
    const folder = { kind: 'directory', name: 'Equations', async *values() { yield pdf; } };
    Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: async () => ({ name: 'Papers', kind: 'directory', async *values() { yield folder; yield { ...pdf, name: 'Overview.pdf' }; } }) });
  });
  await page.locator('.files-tools [data-files=folder]').click();
  await page.waitForFunction(() => document.querySelector('[role=option]')?.textContent.includes('Equations'));
  await page.locator('#file-browser [role=listbox]').focus();
  await page.keyboard.press('l');
  await page.waitForFunction(() => document.querySelector('#file-browser nav')?.textContent.includes('Equations'));
  assert(await page.locator('[role=option]').count() === 1, 'Vim right enters a folder');
  await page.keyboard.press('h');
  await page.waitForFunction(() => document.querySelectorAll('[role=option]').length === 2);
  await page.keyboard.press('j');
  assert((await page.locator('#file-browser [aria-selected=true]').textContent()).includes('Overview.pdf'), 'Vim down selects the next PDF');
  await page.keyboard.press('/'); await page.keyboard.type('Equations');
  await page.waitForFunction(() => document.querySelectorAll('[role=option]').length === 1);
  assert(await page.locator('input[aria-label="Filter files"]').inputValue() === 'Equations', 'Slash focuses incremental folder filtering');
  await page.keyboard.press('Escape');
  assert(!await page.locator('#file-browser').isVisible(), 'Escape closes file browser');
  await page.keyboard.press('o');
  await page.waitForFunction(() => document.querySelectorAll('[role=option]').length === 2);
  assert((await page.locator('#file-browser nav').textContent()).includes('Papers'), 'Connected folder is retained when reopening during the session');
  await page.screenshot({ path: 'output/playwright/file-browser-desktop.png' });
  await page.locator('#file-browser [role=listbox]').focus(); await page.keyboard.press('j'); await page.keyboard.press('Enter');
  await page.waitForFunction(() => !document.querySelector('#file-browser').open && document.title.includes('Overview'));
  assert(true, 'Enter opens the selected PDF through the reader');
  await page.keyboard.press('o');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.locator('#file-browser').evaluate(dialog => dialog.getBoundingClientRect().width <= innerWidth), 'Internal browser fits a narrow viewport');
  await page.evaluate(() => Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: async () => { throw new DOMException('Denied', 'NotAllowedError'); } }));
  await page.locator('.files-tools [data-files=folder]').click();
  await page.waitForFunction(() => document.querySelector('.files-status').textContent.includes('denied'));
  assert(await page.locator('#file-browser').isVisible(), 'Permission denial leaves an actionable internal browser');
  const bytes = await page.evaluate(async () => [...new Uint8Array(await (await fetch('sample.pdf')).arrayBuffer())]);
  const chooserPromise = page.waitForEvent('filechooser');
  await page.locator('[data-files=import]').click();
  const chooser = await chooserPromise;
  await chooser.setFiles({ name: 'Imported.pdf', mimeType: 'application/pdf', buffer: Buffer.from(bytes) });
  await page.waitForFunction(() => document.querySelector('#file-browser [role=option]')?.textContent.includes('Imported.pdf'));
  assert(true, 'Explicit Add PDFs fallback populates the internal selector');
  await page.keyboard.press('Escape');
  console.log(JSON.stringify({ checks }, null, 2));
}
