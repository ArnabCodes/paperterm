async (page) => {
  const base = new URL(page.url()).origin;
  const checks = [], errors = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(String(error)));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(base);
  await page.locator('.showcase').scrollIntoViewIfNeeded();
  assert(await page.locator('[role=tab]').count() === 4, 'Four feature scenes');
  await page.waitForFunction(() => document.querySelector('#tour-toggle').getAttribute('aria-pressed') === 'true');
  assert(await page.locator('#tour-toggle').getAttribute('aria-pressed') === 'true', 'Visible showcase starts a pausable guided tour');
  await page.locator('#stage-reference').click();
  assert(await page.locator('#stage-portal').isVisible(), 'Equation opens content-only portal');
  await page.keyboard.press('Escape');
  assert(await page.locator('#stage-portal').isHidden(), 'Escape closes portal');
  assert(await page.locator('#stage-reference').evaluate(node => node === document.activeElement), 'Portal returns keyboard focus');
  await page.locator('#tab-peek').focus();
  await page.keyboard.press('ArrowDown');
  assert(await page.locator('#tab-flow').getAttribute('aria-selected') === 'true', 'Arrow keys switch feature tabs');
  await page.locator('#scene-flow').focus();
  await page.keyboard.press('j');
  assert(await page.locator('[data-reading-line]').nth(1).evaluate(node => node.classList.contains('current-line')), 'Scoped j moves reading highlight');
  await page.keyboard.press(':');
  assert(await page.locator('#stage-command').isVisible(), 'Colon opens illustrative commands');
  await page.locator('#demo-command').fill('theme');
  assert(await page.locator('#demo-command-results li:visible').count() === 1, 'Command search filters');
  await page.keyboard.press('Escape');
  assert(await page.locator('#stage-command').isHidden(), 'Escape dismisses commands');
  await page.locator('#tab-palette').click();
  await page.locator('.stage-swatches button[data-palette=night]').click();
  assert(await page.locator('.reader-stage').getAttribute('data-palette') === 'night', 'Palette changes illustrated document');
  assert(await page.locator('.stage-swatches [aria-pressed=true]').count() === 1, 'Palette selection stays singular');
  await page.locator('#tab-map').click();
  await page.locator('[data-node="A paper that cites it"]').click();
  assert((await page.locator('#network-detail').textContent()).includes('A paper that cites it'), 'Map nodes reveal connection details');
  assert((await page.locator('.showcase-disclaimer').textContent()).includes('fictional field map'), 'Illustrative graph is distinguished from real citation data');
  await page.screenshot({ path: 'output/playwright/website-motion-map.png' });
  await page.locator('#tab-peek').click();
  await page.locator('#tour-toggle').click();
  await page.waitForTimeout(2600);
  assert(await page.locator('#stage-portal').isVisible(), 'Guided tour demonstrates equation peek');
  await page.locator('#tour-toggle').click();
  assert(await page.locator('.showcase').getAttribute('data-playing') === 'false', 'Pause stops tour');
  await page.locator('#tour-toggle').click();
  await page.locator('#tab-map').click();
  assert(await page.locator('.showcase').getAttribute('data-playing') === 'false', 'Manual interaction stops automatic movement');
  await page.locator('#tour-toggle').click();
  await page.locator('#download').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.showcase').dataset.playing === 'false');
  assert(await page.locator('.showcase').getAttribute('data-playing') === 'false', 'Offscreen tour stops work');
  for (const width of [1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No overflow at ${width}px`);
  }
  await page.screenshot({ path: 'output/playwright/website-motion-mobile.png', fullPage: true });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(base);
  await page.locator('.showcase').scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  assert(await page.locator('#tour-toggle').getAttribute('aria-pressed') === 'false', 'Reduced motion prevents autoplay');
  await page.locator('#tab-peek').click();
  assert(await page.locator('#scene-peek').evaluate(node => getComputedStyle(node).animationName === 'none'), 'Reduced motion removes transitions');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(base);
  await page.locator('.showcase').scrollIntoViewIfNeeded();
  await page.locator('#tab-peek').click();
  await page.screenshot({ path: 'output/playwright/website-motion-desktop.png', fullPage: true });
  const offline = await page.context().browser().newContext();
  const fallback = await offline.newPage();
  await fallback.route('**/release.json', route => route.abort());
  await fallback.goto(base);
  await fallback.locator('#stage-reference').click();
  assert(await fallback.locator('#stage-portal').isVisible(), 'Feature demo does not depend on release metadata');
  await offline.close();
  assert(errors.length === 0, `No JavaScript errors: ${errors.join('; ')}`);
  return { checks: checks.length, passed: checks };
}
