async (page) => {
  page.setDefaultTimeout(10000);
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const pixels = () => page.waitForFunction(() => !document.querySelector('canvas[data-recoloring]')).then(() => page.locator('.canvasWrapper canvas').first().evaluate(canvas => {
    const context = canvas.getContext('2d');
    const sample = (x, y) => Array.from(context.getImageData(Math.floor(canvas.width * x / 612), Math.floor(canvas.height * y / 792), 1, 1).data).slice(0, 3).join(',');
    return { red: sample(132, 312), green: sample(288, 312), blue: sample(444, 312), black: sample(132, 492), white: sample(20, 20) };
  }));
  await page.keyboard.press('Escape');
  await page.locator('#file-input').setInputFiles('output/playwright/fixtures/palette.pdf');
  await page.waitForFunction(() => document.querySelector('#page-total').textContent === '1' && document.querySelector('#loading').hidden && document.querySelector('.canvasWrapper canvas')?.width > 100);
  await page.keyboard.press(',');
  await page.getByRole('button', { name: 'Reset to Paper', exact: true }).click();
  await page.keyboard.press('Escape');
  const original = await pixels();
  assert(original.red === '255,0,0' && original.green === '0,255,0' && original.blue === '0,0,255', 'Original PDF source swatches render without recoloring');
  await page.keyboard.press(',');
  await page.getByRole('button', { name: 'Dracula', exact: true }).click();
  await page.keyboard.press('Escape');
  const dark = await pixels();
  const palette = ['255,85,85', '80,250,123', '241,250,140', '189,147,249', '255,121,198', '139,233,253', '255,110,110', '105,255,148', '255,255,165', '214,172,255', '255,146,223', '164,255,255'];
  assert([dark.red, dark.green, dark.blue].every(color => color.split(',').every(channel => Number(channel) >= 0 && Number(channel) <= 255)) && [dark.red, dark.green, dark.blue].some(color => !palette.includes(color)), 'Colored PDF pixels interpolate between terminal palette swatches instead of snapping');
  assert(new Set([dark.red, dark.green, dark.blue]).size === 3, 'Red, green, and blue diagram colors remain distinct');
  assert(dark.white === '40,42,54' && dark.black === '248,248,242', 'Dark theme preserves exact paper background and readable text endpoints');
  await page.screenshot({ path: 'output/playwright/v05-palette-dark.png', animations: 'disabled' });
  await page.keyboard.press(',');
  await page.getByRole('button', { name: 'Catppuccin Latte', exact: true }).click();
  await page.keyboard.press('Escape');
  const light = await pixels();
  assert(new Set([light.red, light.green, light.blue]).size === 3 && light.white === '239,241,245' && light.black === '76,79,105', 'Light theme also retains distinct colors and correct neutral contrast');
  await page.keyboard.press(',');
  await page.getByRole('button', { name: 'Add a color replacement', exact: true }).click();
  await page.getByLabel('Source color 1', { exact: true }).fill('#ff0000');
  await page.getByLabel('Source color 1', { exact: true }).dispatchEvent('change');
  await page.getByLabel('Replacement color 1', { exact: true }).fill('#123456');
  await page.getByLabel('Replacement color 1', { exact: true }).dispatchEvent('change');
  await page.keyboard.press('Escape');
  assert((await pixels()).red === '18,52,86', 'Explicit source-color replacements override nearest-palette matching');
  await page.keyboard.press(',');
  await page.locator('#recolor-toggle').uncheck();
  await page.keyboard.press('Escape');
  const mapped = await pixels();
  assert(mapped.red === '18,52,86' && mapped.green === '0,255,0' && mapped.blue === '0,0,255', 'Disabling recoloring restores original colors while keeping explicit replacements');
  await page.keyboard.press(',');
  await page.getByRole('button', { name: 'Reset to Paper', exact: true }).click(); await page.keyboard.press('Escape');
  assert((await pixels()).red === original.red, 'Resetting appearance restores the original PDF colors');
  return { passed: checks.length, checks };
}
