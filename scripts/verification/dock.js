async (page) => {
  page.setDefaultTimeout(10000);
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.keyboard.press('Escape');
  await page.mouse.move(700, 300);
  assert(await page.locator('.topbar').count() === 0, 'Fixed top bar is removed');
  assert(await page.locator('#reader-toolbar').isVisible() && await page.locator('.dock-more').getAttribute('aria-hidden') === 'true', 'Compact dock stays visible while extra controls remain inert');
  assert(await page.locator('#sidebar').getAttribute('aria-hidden') === 'true', 'Sidebar starts collapsed');
  const original = await page.locator('#viewer-container').boundingBox();
  assert(original.y === 0 && original.height === 960, 'PDF viewport fills the window behind controls');
  await page.mouse.move(720, 952);
  await page.waitForFunction(() => document.body.classList.contains('dock-visible'));
  const dock = page.locator('#reader-toolbar');
  await dock.waitFor({ state: 'visible' });
  assert(await dock.isVisible(), 'Bottom-edge mouse movement reveals the dock');
  const surface = await dock.evaluate(node => ({ blur: getComputedStyle(node).backdropFilter, border: getComputedStyle(node).borderTopWidth, bg: getComputedStyle(node).backgroundColor }));
  assert(surface.blur.includes('blur') && surface.border === '0px' && surface.bg.includes('0.24'), 'Dock is borderless, translucent, and blurred');
  await page.screenshot({ path: 'output/playwright/dock-revealed.png', animations: 'disabled' });
  await page.mouse.move(720, 300);
  await page.waitForFunction(() => !document.body.classList.contains('dock-visible'));
  assert(await dock.isVisible() && await page.locator('.dock-more').getAttribute('aria-hidden') === 'true', 'Dock returns to compact controls after mouse leaves');
  await page.mouse.move(4, 400);
  await page.waitForFunction(() => document.body.classList.contains('sidebar-visible'));
  await page.locator('#sidebar').waitFor({ state: 'visible' });
  assert(await page.locator('#sidebar').isVisible(), 'Left-edge mouse movement reveals sidebar');
  const expanded = await page.locator('#viewer-container').boundingBox();
  assert(expanded.width === original.width && expanded.x === original.x, 'Sidebar overlays the page without resizing it');
  await page.screenshot({ path: 'output/playwright/sidebar-revealed.png', animations: 'disabled' });
  await page.mouse.move(720, 300);
  await page.waitForFunction(() => !document.body.classList.contains('sidebar-visible'));
  await page.keyboard.press('t');
  assert(await page.locator('body').evaluate(node => node.classList.contains('sidebar-visible')), 'Keyboard shortcut opens sidebar');
  await page.keyboard.press('Escape');
  await page.mouse.move(721, 300);
  await page.keyboard.press('F6');
  await page.waitForTimeout(450);
  assert(await dock.evaluate(node => node.contains(document.activeElement)), 'F6 exposes dock with keyboard focus');
  await page.keyboard.press('Escape');
  await page.keyboard.press(':');
  const input = page.getByRole('combobox', { name: 'Find a command', exact: true });
  await input.waitFor();
  assert(await page.getByRole('option').count() > 50, 'Colon exposes actions, settings, and every theme');
  assert(await page.locator('#palette').evaluate(node => getComputedStyle(node).borderTopWidth) === '0px', 'Command popup has no border');
  await input.fill('3'); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#page-current').textContent === '3');
  assert(true, 'Numeric command still jumps directly to a page');
  await page.keyboard.press('j');
  assert(!await page.locator('#viewer-container').evaluate(node => node.classList.contains('mouse-scrolling')), 'Keyboard scrolling does not reveal scrollbars');
  await page.mouse.move(800, 450); await page.mouse.wheel(0, 240);
  await page.waitForFunction(() => document.querySelector('#viewer-container').classList.contains('mouse-scrolling'));
  assert(true, 'Mouse wheel temporarily reveals scrollbar');
  await page.waitForFunction(() => !document.querySelector('#viewer-container').classList.contains('mouse-scrolling'));
  assert(true, 'Scrollbar hides when wheel activity ends');
  await page.keyboard.press(',');
  assert(await page.locator('.theme-options [data-theme]').count() === 23, 'Twenty terminal themes coexist with three original presets');
  await page.getByRole('button', { name: 'Light', exact: true }).click();
  assert(await page.locator('.theme-options [data-theme]:visible').count() === 10, 'Light filter contains eight new light themes and two original presets');
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  assert(await page.locator('.theme-options [data-theme]:visible').count() === 13, 'Dark filter contains twelve new dark themes and Night');
  await page.getByRole('button', { name: 'All', exact: true }).click();
  const ids = await page.locator('.theme-options [data-theme]').evaluateAll(nodes => nodes.map(node => node.dataset.theme));
  for (const id of ids) {
    await page.locator(`.theme-options [data-theme="${id}"]`).click();
    if (await page.locator('html').getAttribute('data-theme') !== id) throw new Error(`Failed to apply ${id}`);
    const selected = page.locator(`.theme-options [data-theme="${id}"]`);
    if (await selected.evaluate(node => getComputedStyle(node).outlineStyle) !== 'none') throw new Error(`Unexpected outline for ${id}`);
  }
  assert(true, 'All 23 themes apply with borderless selection');
  await page.getByRole('button', { name: 'Catppuccin Mocha', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/terminal-themes.png', animations: 'disabled' });
  await page.keyboard.press('Escape'); await page.reload();
  await page.waitForFunction(() => document.querySelector('#loading').hidden);
  assert(await page.locator('html').getAttribute('data-theme') === 'catppuccin-mocha', 'Terminal theme persists across reload');
  await page.keyboard.press(':');
  await page.getByRole('combobox', { name: 'Find a command', exact: true }).fill('theme paper');
  await page.keyboard.press('Enter');
  assert(await page.locator('html').getAttribute('data-theme') === 'paper', 'Theme selection is available from colon menu');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.keyboard.press('F6');
  assert(await dock.evaluate(node => node.getBoundingClientRect().left >= 0 && node.getBoundingClientRect().right <= innerWidth) && await page.locator('.dock-more-content').evaluate(node => node.scrollWidth <= node.clientWidth), 'Floating dock fits a 390px window');
  await page.screenshot({ path: 'output/playwright/dock-compact.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1440, height: 960 });
  return { passed: checks.length, checks };
}
